create table ESPECIALIDADES (
   id_especialidad   NUMBER        PRIMARY KEY,
   nombre            VARCHAR2(20) NOT NULL);
   
create table MEDICOS (
   id_medico            NUMBER        PRIMARY KEY,
   nombre               VARCHAR2(25)  NOT NULL,
   salario              NUMBER(10,2)  NOT NULL,
   c_guardias           NUMBER(10,2)  DEFAULT 0,
   contratacion         DATE          NOT NULL,
   id_especialidad      NUMBER        NOT NULL,
   FOREIGN KEY (id_especialidad) REFERENCES ESPECIALIDADES(id_especialidad));
   
create table PACIENTES (
   id_paciente      NUMBER        PRIMARY KEY,
   nombre           VARCHAR2(15)  NOT NULL,
   categoria        CHAR(1)  CHECK (categoria IN ('A','B','C')),
   fecha_nacimiento DATE);
   
create table HOSPITALIZACIONES (
   id_hosp        NUMBER        PRIMARY KEY,
   id_paciente    NUMBER        NOT NULL,
   id_medico      NUMBER        NOT NULL,
   horas_estancia NUMBER(6,2),
   coste          NUMBER(10,2),
   FOREIGN KEY (id_paciente) REFERENCES PACIENTES(id_paciente),
   FOREIGN KEY (id_medico)   REFERENCES MEDICOS(id_medico));
   
